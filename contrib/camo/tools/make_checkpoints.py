"""Generate compiled-in checkpoints for src/checkpoints/checkpoints.cpp from running CAMO nodes.

A checkpoint pins the block hash (and cumulative difficulty) at a height. Nodes refuse any chain that disagrees and
roll back if their own copy does, so an attacker with rented hashrate can't rewrite history below the last
checkpoint. The launch plan: first checkpoints in v1.0.1 (Day 7), then with each point release for 3 months.

  # preview, from the seed nodes (SSH, like camo_health.py); all nodes must agree on every hash:
  python3 make_checkpoints.py seed1=ssh://root@IP1 seed2=ssh://root@IP2 seed3=ssh://root@IP3
  # write them into src/checkpoints/checkpoints.cpp:
  python3 make_checkpoints.py --write seed1=ssh://root@IP1 seed2=ssh://root@IP2 seed3=ssh://root@IP3

Safety rules (built in):
- Only blocks at least --min-depth below every node's tip (default 720, about 12 hours) are checkpointed.
- Every node queried must report the same hash and cumulative difficulty at every checkpoint height; one
  disagreement aborts. Use nodes you run, in different places.
- Existing checkpoints are never changed or removed. They are re-checked against the chain first; a mismatch aborts
  (it would mean a fork, or a wrong node). New ones are only appended above the highest existing one.
- Block 1 (the allocation block) is always checkpointed, then every --every blocks, plus the most recent multiple of
  --step that is deep enough.
After --write: rebuild, run the unit tests and a node against the live chain (it logs "CHECKPOINT PASSED"), commit.

Note: like Monero, camod enforces compiled-in checkpoints on MAINNET only; the testnet/stagenet sections are used
by wallets. Tested Nov 4 on a local mainnet-mode chain: a syncing node passed every checkpoint, and a node mining a
different chain was refused at block 1 ("CHECKPOINT VALIDATION FAILED").
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from camo_health import NETS, Node  # noqa: E402  (same directory)

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
CPP = os.path.join(REPO, 'src', 'checkpoints', 'checkpoints.cpp')
FUNC_RE = re.compile(r'(  bool checkpoints::init_default_checkpoints\(network_type nettype\)\n  \{\n)(.*?)(\n  \}\n)', re.S)
LINE_RE = re.compile(r'ADD_CHECKPOINT2\((\d+),\s*"([0-9a-f]{64})",\s*"(0x[0-9a-fA-F]+)"\);')
SECTIONS = ('testnet', 'stagenet', 'mainnet')


def parse_existing(body):
    """Split init_default_checkpoints' body into {network: [(height, hash, diff)]}."""
    out = {n: [] for n in SECTIONS}
    current = 'mainnet'  # lines after the last `if` block are mainnet's
    for line in body.split('\n'):
        if 'nettype == TESTNET' in line:
            current = 'testnet'
        elif 'nettype == STAGENET' in line:
            current = 'stagenet'
        elif current != 'mainnet' and line.strip() == 'return true;':
            current = 'mainnet'
        m = LINE_RE.search(line)
        if m:
            out[current].append((int(m.group(1)), m.group(2), m.group(3).lower()))
    return out


def render(points):
    def lines(net):
        return ''.join('      ADD_CHECKPOINT2(%d, "%s", "%s");\n' % p for p in sorted(points[net]))
    mainnet = lines('mainnet').replace('      ADD', '    ADD')
    return ('    // CAMO checkpoints: block hash + cumulative difficulty, generated by contrib/camo/tools/make_checkpoints.py.\n'
            '    // Append only: never change or remove a line once released.\n'
            '    if (nettype == TESTNET)\n    {\n' + lines('testnet') + '      return true;\n    }\n'
            '    if (nettype == STAGENET)\n    {\n' + lines('stagenet') + '      return true;\n    }\n'
            + mainnet + '    return true;')


def header(node, height):
    h = node.rpc('get_block_header_by_height', height=height)['block_header']
    diff = h.get('wide_cumulative_difficulty') or hex(h['cumulative_difficulty'])
    return h['hash'], '0x' + diff[2:].lower().lstrip('0') if diff.startswith('0x') else hex(int(diff))


def main():
    p = argparse.ArgumentParser(description=__doc__.split('\n')[0],
                                formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__.split('\n', 2)[2])
    g = p.add_mutually_exclusive_group()
    for net in ('testnet', 'stagenet'):
        g.add_argument('--' + net, dest='net', action='store_const', const=net)
    p.set_defaults(net='mainnet')
    p.add_argument('nodes', nargs='+', help='http://host:port or ssh://user@host[:rpcport], optionally name=...')
    p.add_argument('--min-depth', type=int, default=720, help='blocks below every tip (default 720 = ~12 h)')
    p.add_argument('--every', type=int, default=10000, help='regular checkpoint interval (default 10000 = ~1 week)')
    p.add_argument('--step', type=int, default=1000, help='round the newest checkpoint down to this (default 1000)')
    p.add_argument('--write', action='store_true', help='update src/checkpoints/checkpoints.cpp (default: print)')
    p.add_argument('--file', default=CPP, help=argparse.SUPPRESS)
    p.add_argument('--timeout', type=int, default=15, help=argparse.SUPPRESS)
    args = p.parse_args()
    if args.min_depth < 10 and args.net == 'mainnet':
        sys.exit('refusing --min-depth below 10 on mainnet')

    nodes = [Node(s, NETS[args.net][0], args.timeout) for s in args.nodes]
    tips = {}
    for n in nodes:
        i = n.info()
        if i.get('nettype') != NETS[args.net][2]:
            sys.exit('%s is on %s, not %s' % (n.name, i.get('nettype'), args.net))
        if i.get('busy_syncing') or not i.get('synchronized', True):
            sys.exit('%s is still syncing; try again when it has caught up' % n.name)
        g = n.rpc('get_block_header_by_height', height=0)['block_header']['hash']
        if g != NETS[args.net][1]:
            sys.exit('%s: genesis %s is not CAMO %s genesis' % (n.name, g, args.net))
        tips[n.name] = i['height'] - 1
    deepest = min(tips.values()) - args.min_depth
    print('tips: %s; checkpointing up to height %d (min depth %d)' % (
        ', '.join('%s %d' % kv for kv in tips.items()), deepest, args.min_depth), file=sys.stderr)

    src = open(args.file).read()
    m = FUNC_RE.search(src)
    if not m:
        sys.exit('could not find init_default_checkpoints in ' + args.file)
    points = parse_existing(m.group(2))
    existing = points[args.net]
    top = max((h for h, _, _ in existing), default=0)

    def agreed(height):
        seen = {n.name: header(n, height) for n in nodes}
        if len(set(seen.values())) != 1:
            sys.exit('ABORT: nodes disagree at height %d: %s' % (height, seen))
        return next(iter(seen.values()))

    for h, hsh, diff in existing:  # re-check what's already compiled in
        if h <= deepest + args.min_depth:
            got = agreed(h)
            if got != (hsh, diff):
                sys.exit('ABORT: existing checkpoint %d (%s, %s) does not match the chain (%s, %s)' % ((h, hsh, diff) + got))
    if existing:
        print('existing %s checkpoints: %d, up to height %d, all match the chain' % (args.net, len(existing), top),
              file=sys.stderr)

    want = {1} | set(range(args.every, deepest + 1, args.every))
    if deepest >= args.step:
        want.add(deepest // args.step * args.step)
    new = sorted(h for h in want if top < h <= deepest)
    added = [(h,) + agreed(h) for h in new]
    if not added:
        print('nothing to add (newest eligible height %d, highest existing %d)' % (deepest, top), file=sys.stderr)
        return
    points[args.net] = existing + added
    for a in added:
        print('    ADD_CHECKPOINT2(%d, "%s", "%s");' % a)
    if args.write:
        with open(args.file, 'w') as f:
            f.write(src[:m.start(2)] + render(points) + src[m.end(2):])
        print('wrote %d new %s checkpoint(s) to %s' % (len(added), args.net, os.path.relpath(args.file, REPO)),
              file=sys.stderr)


if __name__ == '__main__':
    try:
        main()
    except (OSError, RuntimeError, ValueError, KeyError) as e:  # unreachable node, RPC error, bad reply
        sys.exit('ERROR: %s' % e)
