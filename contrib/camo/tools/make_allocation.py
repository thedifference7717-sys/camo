#!/usr/bin/env python3
"""Build CAMO's block-1 allocation transaction and write src/cryptonote_core/camo_allocation.h.

Why block 1 and not genesis: wallets treat the genesis block as already known and never scan it,
and a version-1 genesis output can't be ring-signed with 15 decoys. Block 1's coinbase is a normal
version-2 (RingCT) coinbase, so wallets find it and its outputs are spent like any mined coins.
A consensus rule (blockchain.cpp) requires block 1's coinbase to be exactly this transaction.

Usage:
  python3 make_allocation.py --founder <addr> --marketing <addr> [--total 640000] [--marketing-amount 54400] [--burn-pct 15]
Addresses can be CAMO (C...) or Monero (4...) addresses from the same seed. Only PUBLIC addresses are used.
"""
import argparse, importlib.util, os

HERE = os.path.dirname(os.path.abspath(__file__))
def _load(name, file):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, file))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m
mg = _load("mg", "make_genesis.py")
mb = _load("mb", "make_burn_address.py")

UNLOCK_WINDOW = 60   # CRYPTONOTE_MINED_MONEY_UNLOCK_WINDOW
HEIGHT = 1

def build_coinbase_v2(outputs):
    """outputs: list of (spend_pub, view_pub, amount_atomic). Returns tx hex (v2 coinbase, RCTTypeNull)."""
    r = int.from_bytes(os.urandom(64), "little") % mg.L
    R = mg.enc(mg.mul(r, mg.G))
    tx = bytes([0x02]) + mg.varint(HEIGHT + UNLOCK_WINDOW) + b"\x01\xff" + mg.varint(HEIGHT) + mg.varint(len(outputs))
    for i, (spend, view, amt) in enumerate(outputs):
        D = mg.enc(mg.mul(8, mg.mul(r, mg.dec(view))))
        view_tag = mg.keccak256(b"view_tag" + D + mg.varint(i))[:1]
        tx += mg.varint(amt) + b"\x03" + mg.output_key(r, view, spend, i) + view_tag   # txout_to_tagged_key (block 1 runs hard fork v16)
    tx += b"\x21\x01" + R      # extra: tx public key
    tx += b"\x00"              # rct_signatures.type = RCTTypeNull
    return tx.hex()

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--founder", required=True); ap.add_argument("--marketing", required=True)
    ap.add_argument("--total", type=float, default=640000); ap.add_argument("--marketing-amount", type=float, default=54400)
    ap.add_argument("--burn-pct", type=float, default=15)
    ap.add_argument("--header", default=os.path.join(HERE, "..", "..", "..", "src", "cryptonote_core", "camo_allocation.h"))
    a = ap.parse_args()
    burn = a.total * a.burn_pct / 100
    founder = a.total - burn - a.marketing_amount
    atomic = lambda x: int(round(x * 10**12))
    _, fs, fv = mg.parse_address(a.founder); _, ms, mv = mg.parse_address(a.marketing)
    bs, _, bv, _ = mb.burn_keys()
    outs = [(fs, fv, atomic(founder)), (ms, mv, atomic(a.marketing_amount)), (bs, bv, atomic(burn))]
    nets = {}
    for net in ("mainnet", "testnet", "stagenet"):
        nets[net] = build_coinbase_v2(outs)   # fresh one-time key per network
    print(f"founder   {founder:>12,.2f} CAMO -> {mg.camo_address(fs, fv, 'mainnet')}")
    print(f"marketing {a.marketing_amount:>12,.2f} CAMO -> {mg.camo_address(ms, mv, 'mainnet')}")
    print(f"burn      {burn:>12,.2f} CAMO -> {mg.camo_address(bs, bv, 'mainnet')}")
    hdr = f'''// Generated by contrib/camo/tools/make_allocation.py -- do not edit by hand.
// CAMO block-1 allocation: {founder:,.0f} founder, {a.marketing_amount:,.0f} marketing, {burn:,.0f} provably burned.
// Consensus: block 1's coinbase must be exactly this transaction (see Blockchain::validate_miner_transaction).
#pragma once
#include <string>
#include "cryptonote_config.h"

namespace camo
{{
  constexpr uint64_t ALLOCATION_HEIGHT = 1;
  inline const char* allocation_tx_hex(cryptonote::network_type nettype)
  {{
    switch (nettype)
    {{
      case cryptonote::TESTNET:  return "{nets['testnet']}";
      case cryptonote::STAGENET: return "{nets['stagenet']}";
      default:                   return "{nets['mainnet']}"; // MAINNET and FAKECHAIN (regtest)
    }}
  }}
}}
'''
    path = os.path.abspath(a.header)
    open(path, "w").write(hdr)
    print("wrote", path)

if __name__ == "__main__":
    main()
